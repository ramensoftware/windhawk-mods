static void LoadSettings() {
    Settings s;
    for (int i = 0;; i++) {
        Customization c;
        c.bootEntry = WindhawkUtils::StringSetting::make(L"customizations[%d].bootEntry", i).get();
        if (c.bootEntry.empty()) break;  // end of the list
        c.label = WindhawkUtils::StringSetting::make(L"customizations[%d].label", i).get();
        c.icon = WindhawkUtils::StringSetting::make(L"customizations[%d].icon", i).get();
        s.customizations.push_back(std::move(c));
    }
    std::lock_guard<std::mutex> lock(g_mutex);
    g_settings = std::move(s);
}

// Hidden systems are chosen in the window shown after a scan, and kept in the
// mod storage as lowercase names: hiddenCount, then hidden0, hidden1...
static void LoadHidden() {
    std::vector<std::wstring> hidden;
    int count = Wh_GetIntValue(L"hiddenCount", 0);
    for (int i = 0; i < count; i++) {
        std::wstring key = L"hidden" + std::to_wstring(i);
        WCHAR name[512] = L"";
        Wh_GetStringValue(key.c_str(), name, ARRAYSIZE(name));
        if (name[0]) hidden.push_back(name);
    }
    std::lock_guard<std::mutex> lock(g_mutex);
    g_hidden = std::move(hidden);
}

static void SaveHidden(std::vector<std::wstring> hidden) {
    int oldCount = Wh_GetIntValue(L"hiddenCount", 0);
    for (int i = 0; i < (int)hidden.size(); i++) {
        Wh_SetStringValue((L"hidden" + std::to_wstring(i)).c_str(), hidden[i].c_str());
    }
    for (int i = (int)hidden.size(); i < oldCount; i++) {
        Wh_DeleteValue((L"hidden" + std::to_wstring(i)).c_str());
    }
    Wh_SetIntValue(L"hiddenCount", (int)hidden.size());
    std::lock_guard<std::mutex> lock(g_mutex);
    g_hidden = std::move(hidden);
}

static bool Contains(std::vector<std::wstring> const& list, std::wstring const& value) {
    return std::find(list.begin(), list.end(), value) != list.end();
}

static std::wstring DisplayName(std::wstring name) {
    if (!name.empty()) name[0] = towupper(name[0]);  // "ubuntu" -> "Ubuntu"
    return name;
}

static const IconDef* FindIcon(std::wstring const& id) {
    for (auto const& def : kIcons) {
        if (id == def.id) return &def;
    }
    return nullptr;
}

// Builds the list of items to show, from the detected systems and the settings.
static std::vector<MenuEntry> BuildMenuEntries() {
    Settings s;
    std::vector<DetectedSystem> detected;
    std::vector<std::wstring> hidden;
    {
        std::lock_guard<std::mutex> lock(g_mutex);
        s = g_settings;
        detected = g_detected;
        hidden = g_hidden;
    }
    bool fr = IsFrench();
    std::vector<MenuEntry> entries;
    for (auto const& sys : detected) {
        if (Contains(hidden, ToLower(sys.name))) continue;
        const Customization* custom = nullptr;
        for (auto const& c : s.customizations) {
            if (ToLower(c.bootEntry) == ToLower(sys.name) ||
                ToLower(c.bootEntry) == ToLower(DisplayName(sys.name))) {
                custom = &c;
            }
        }
        MenuEntry e;
        e.taskName = sys.taskName;
        e.label = custom && !custom->label.empty()
                      ? custom->label
                      : (fr ? L"Redémarrer sur " : L"Restart to ") + DisplayName(sys.name);

        std::wstring iconId = custom ? custom->icon : L"auto";
        if (iconId.empty() || iconId == L"auto") {
            std::wstring lower = ToLower(sys.name);
            iconId = L"linux";
            for (auto const& def : kIcons) {
                if (def.match[0] && lower.find(def.match) != std::wstring::npos) {
                    iconId = def.id;
                    break;
                }
            }
        }
        if (iconId != L"restart") {
            if (auto def = FindIcon(iconId)) e.iconPath = def->path;
        }
        entries.push_back(std::move(e));
    }
    return entries;
}

