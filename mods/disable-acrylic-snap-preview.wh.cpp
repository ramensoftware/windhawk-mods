AtlasMargins AtlasFrameInsets(const AtlasSizes& sizes) {
	return { sizes[0].cx, sizes[2].cx, sizes[1].cy, sizes[6].cy };
}

AtlasRecords BuildAtlasRecords(const AtlasSizes& sizes) {
	const int inf = g_AtlasNoOverride;
	const AtlasMargins frameInsets = AtlasFrameInsets(sizes);
	const int left = frameInsets.cxLeftWidth;
	const int right = frameInsets.cxRightWidth;
	const int top = frameInsets.cyTopHeight;
	const int bottom = frameInsets.cyBottomHeight;
	const int width = left;
	return {
		AtlasRecord{ -left, inf, -top, inf, width, width },
		AtlasRecord{ 0, 0, -top, inf, inf, width },
		AtlasRecord{ inf, -right, -top, inf, width, width },
		AtlasRecord{ -left, inf, width - top, width - bottom, width, inf },
		AtlasRecord{ inf, -right, width - top, width - bottom, width, inf },
		AtlasRecord{ -left, inf, inf, -bottom, width, width },
		AtlasRecord{ 0, 0, inf, -bottom, inf, width },
		AtlasRecord{ inf, -right, inf, -bottom, width, width },
		AtlasRecord{ width - left, width - right, width - top, width - bottom, inf, inf },
		AtlasRecord{ -(sizes[9].cx + left), inf, -sizes[0].cy, -sizes[5].cy, sizes[9].cx, inf },
		AtlasRecord{ inf, -(sizes[10].cx + right), -top, -bottom, sizes[10].cx, inf },
		AtlasRecord{ -(sizes[9].cx + left), -(sizes[10].cx + right),
			-(sizes[11].cy + top), inf, inf, sizes[11].cy },
		AtlasRecord{ -(sizes[9].cx + sizes[5].cx), -(sizes[10].cx + sizes[7].cx),
			inf, -(sizes[12].cy + bottom), inf, sizes[12].cy }
	};
}

unsigned int AtlasHiddenMargins(const AtlasRecord& record) {
	return (record[3] == g_AtlasNoOverride ? 8u : 0u) |
		(record[0] == g_AtlasNoOverride ? 1u : 0u) |
		(record[2] == g_AtlasNoOverride ? 4u : 0u) |
		(record[1] == g_AtlasNoOverride ? 2u : 0u);
}

void* SnapReferenceVisual(void* list, void* owner) {
	if (g_Profile->useRelatedReferenceVisual) {
		if (void* related = g_FindWindowDataByHwnd(list, WindowRelatedHwnd(owner))) {
			if (void* visual = WindowVisual(related))
				return visual;
		}
	}
	return WindowVisual(owner);
}

bool UpdateAtlasGeometry(void* list, void* owner, void* sheet, double opacity) {
	if (!g_Atlas.visual || !sheet)
		return false;
	if (!list)
		list = g_Atlas.list;
	if (!owner)
		owner = g_Atlas.owner;
	if (!list || !owner)
		return false;
	RECT rect = SheetRect(sheet);
	int width = std::max(0L, rect.right - rect.left);
	int height = std::max(0L, rect.bottom - rect.top);
	POINT offset{ rect.left, rect.top };
	g_SetVisualOffset(g_Atlas.visual, &offset);
	if (FAILED(SetVisualSize(g_Atlas.visual, width, height)))
		return false;
	g_SetOpacity(g_Atlas.visual, opacity);
	void* root = g_GetRootVisualForDesktop(list, WindowDesktopId(owner));
	void* reference = SnapReferenceVisual(list, owner);
	if (!root || !reference)
		return false;
	if (!g_Atlas.attached || g_Atlas.list != list || g_Atlas.owner != owner) {
		g_RemoveSelfFromParent(g_Atlas.visual);
		HRESULT result = InsertVisualRelative(root, g_Atlas.visual, reference, false);
		if (FAILED(result)) {
			LogFailure(g_AtlasFailureLogged, L"Positioning the Windows 10 atlas visual failed", result);
			return false;
		}
		g_Atlas.list = list;
		g_Atlas.owner = owner;
		g_Atlas.attached = true;
	}
	return true;
}

bool EnsureAtlas(void* list, void* owner, void* sheet, double opacity) {
	void* border = g_Atlas.sheet == sheet ? g_Atlas.border : FindSheetBorder(sheet);
	if (!border)
		return false;
	if (g_Atlas.visual && g_Atlas.sheet == sheet) {
		g_SetBorderContent(border, nullptr);
		g_EnableBorder(border, false);
		UpdateAtlasGeometry(list, owner, sheet, opacity);
		return true;
	}
	if (g_Atlas.visual)
		ResetAtlasResources();

	void* visual{};
	HRESULT result = g_CreateAtlasVisual(&visual);
	if (FAILED(result))
		return false;
	void* frame = g_WindowFramesStorage && *g_WindowFramesStorage ?
		reinterpret_cast<void**>(*g_WindowFramesStorage)[0] : nullptr;
	AtlasSizes sizes{};
	AtlasSources sources{};
	const double scale = DisplayScale();
	for (unsigned int i = 0; i < g_AtlasPartCount; ++i) {
		sources[i] = frame ? g_GetWindowFramePart(frame, i + 9) : nullptr;
		if (sources[i]) {
			SIZE raw = BitmapSize(sources[i]);
			sizes[i].cx = static_cast<LONG>(static_cast<double>(raw.cx) * scale);
			sizes[i].cy = static_cast<LONG>(static_cast<double>(raw.cy) * scale);
		}
	}
	const auto records = BuildAtlasRecords(sizes);
	for (unsigned int i = 0; i < g_AtlasPartCount; ++i) {
		void* image{};
		result = g_CreateAtlasImage(&image);
		if (FAILED(result))
			break;
		result = g_InsertAtlasImage(visual, image, i);
		if (SUCCEEDED(result)) {
			const auto& record = records[i];
			g_SetAtlasBitmapSource(image,
				sizes[i].cx > 0 && sizes[i].cy > 0 ? sources[i] : nullptr);
			AtlasMargins margins{ record[0], record[1], record[2], record[3] };
			g_SetAtlasInset(image, &margins);
			if (record[4] != g_AtlasNoOverride || record[5] != g_AtlasNoOverride) {
				SIZE imageSize = sizes[i];
				if (record[4] != g_AtlasNoOverride)
					imageSize.cx = record[4];
				if (record[5] != g_AtlasNoOverride)
					imageSize.cy = record[5];
				g_SetAtlasSize(image, &imageSize);
			}
			SetAtlasHiddenMargins(image, AtlasHiddenMargins(record));
		}
		g_ReleaseObject(image);
		if (FAILED(result))
			break;
	}
	if (FAILED(result)) {
		ReleaseAtlasVisual(visual);
		LogFailure(g_AtlasFailureLogged, L"Windows 10 atlas visual creation failed", result);
		return false;
	}
	result = g_SetBorderContent(border, nullptr);
	if (SUCCEEDED(result))
		result = g_EnableBorder(border, false);
	if (FAILED(result)) {
		ReleaseAtlasVisual(visual);
		LogFailure(g_BorderDisableFailureLogged, L"Replacing the Win11 snap border failed", result);
		return false;
	}
	g_Atlas.visual = visual;
	g_Atlas.sheet = sheet;
	g_Atlas.list = list;
	g_Atlas.owner = owner;
	g_Atlas.border = border;
	g_Atlas.frameInsets = AtlasFrameInsets(sizes);
	g_Atlas.attached = false;
	g_AtlasFailureLogged = false;
	g_BorderDisableFailureLogged = false;
	return UpdateAtlasGeometry(list, owner, sheet, opacity);
}

void ReleaseObjectIfPresent(void*& object) {
	if (!object)
		return;
	g_ReleaseObject(object);
	object = nullptr;
}

bool TryReadDwmDword(HKEY root, const wchar_t* name, DWORD& value) {
	DWORD size = sizeof(value);
	return RegGetValueW(
		root,
		g_DwmRegistryPath,
		name,
		RRF_RT_REG_DWORD,
		nullptr,
		&value,
		&size) == ERROR_SUCCESS;
}

DWORD ReadDwmDword(const wchar_t* name, DWORD defaultValue) {
	DWORD value{};
	if (TryReadDwmDword(HKEY_CURRENT_USER, name, value) ||
		TryReadDwmDword(HKEY_LOCAL_MACHINE, name, value)) {
		return value;
	}
	return defaultValue;
}

float ReflectionMarker() {
	float marker{};
	DWORD bits = g_ReflectionMarkerBits;
	std::memcpy(&marker, &bits, sizeof(marker));
	return marker;
}

// OpenGlass decodes this alpha marker in GlassInfra::AlphaChannelReinterpreter;
// keep the marker bits in sync with that encoding.
double ReflectionBrushOpacity(double opacity) {
	opacity = std::clamp(opacity, 0.0, 1.0);
	return opacity >= 1.0 ? ReflectionMarker() : opacity;
}

void ResetReflectionResources() {
	if (g_Reflection.visual) {
		g_RemoveSelfFromParent(g_Reflection.visual);
		ReleaseObjectIfPresent(g_Reflection.visual);
	}
	ReleaseObjectIfPresent(g_Reflection.brush);
	ReleaseObjectIfPresent(g_Reflection.geometry);
	g_Reflection = {};
}

void RefreshReflectionSettings() {
	DWORD policy = ReadDwmDword(L"ColorizationGlassReflectionPolicy", 0xFFFFFFFF);
	bool requested = (policy & g_AnimatedGlassSheetReflectionPolicy) != 0;
	bool available = GetModuleHandleW(L"OpenGlass.dll") != nullptr;
	g_ReflectionRoundRectRadius = static_cast<int>(ReadDwmDword(L"RoundRectRadius", 0));
	g_ReflectionEnabled = requested && available;
	if (!g_ReflectionEnabled && g_Reflection.visual)
		ResetReflectionResources();
	if (requested && !available) {
		if (!g_ReflectionUnavailableLogged) {
			Wh_Log(L"Snap reflection is enabled but OpenGlass.dll is not loaded");
			g_ReflectionUnavailableLogged = true;
		}
	} else {
		g_ReflectionUnavailableLogged = false;
	}
}

HRGN CreateReflectionRegion(int width, int height) {
	int left = -g_Atlas.frameInsets.cxLeftWidth;
	int top = -g_Atlas.frameInsets.cyTopHeight;
	int right = width + g_Atlas.frameInsets.cxRightWidth;
	int bottom = height + g_Atlas.frameInsets.cyBottomHeight;
	if (g_ReflectionRoundRectRadius > 0) {
		return CreateRoundRectRgn(
			left,
			top,
			right,
			bottom,
			g_ReflectionRoundRectRadius,
			g_ReflectionRoundRectRadius);
	}
	return CreateRectRgn(left, top, right, bottom);
}

bool UpdateReflectionGeometry(void* list, void* owner, void* sheet, double opacity) {
	if (!g_ReflectionEnabled || !g_Reflection.visual || !g_Reflection.brush ||
		!g_Reflection.geometry || !sheet) {
		return false;
	}
	if (!list)
		list = g_Reflection.list;
	if (!owner)
		owner = g_Reflection.owner;
	if (!list || !owner)
		return false;

	RECT rect = SheetRect(sheet);
	int width = std::max(0L, rect.right - rect.left);
	int height = std::max(0L, rect.bottom - rect.top);
	POINT offset{ rect.left, rect.top };
	g_SetVisualOffset(g_Reflection.visual, &offset);
	if (FAILED(SetVisualSize(g_Reflection.visual, width, height)))
		return false;
	// OpenGlass realizes this brush outside the normal visual-opacity path.
	// Encode the sheet alpha in the brush during fades to match the original
	// CAnimatedGlassSheet child visual behavior.
	g_SetOpacity(g_Reflection.visual, 1.0);

	void* root = g_GetRootVisualForDesktop(list, WindowDesktopId(owner));
	if (!root)
		return false;
	if (!g_Reflection.attached || g_Reflection.list != list || g_Reflection.owner != owner) {
		void* reference = g_Atlas.visual && g_Atlas.attached ?
			g_Atlas.visual : SnapReferenceVisual(list, owner);
		bool insertAfter = reference == g_Atlas.visual;
		if (!reference)
			return false;
		g_RemoveSelfFromParent(g_Reflection.visual);
		HRESULT result = InsertVisualRelative(
			root, g_Reflection.visual, reference, insertAfter);
		if (FAILED(result)) {
			LogFailure(g_ReflectionFailureLogged, L"Positioning the snap reflection visual failed", result);
			return false;
		}
		g_Reflection.list = list;
		g_Reflection.owner = owner;
		g_Reflection.attached = true;
	}

	FloatRect viewport {
		static_cast<float>(GetSystemMetrics(SM_XVIRTUALSCREEN) - rect.left),
		static_cast<float>(GetSystemMetrics(SM_YVIRTUALSCREEN) - rect.top),
		0.0f,
		0.0f
	};
	viewport.right = viewport.left + static_cast<float>(GetSystemMetrics(SM_CXVIRTUALSCREEN));
	viewport.bottom = viewport.top + static_cast<float>(GetSystemMetrics(SM_CYVIRTUALSCREEN));
	FloatRect source{};
	HRESULT result = g_UpdateImageLegacyMilBrush(
		g_Reflection.brush,
		ReflectionBrushOpacity(opacity),
		&viewport,
		&source,
		nullptr,
		0,
		0,
		nullptr,
		nullptr,
		0,
		0,
		0,
		0,
		nullptr);
	if (SUCCEEDED(result))
		result = g_ValidateRenderDataVisual(g_Reflection.visual);
	if (SUCCEEDED(result)) {
		HRGN region = CreateReflectionRegion(width, height);
		if (!region) {
			result = HRESULT_FROM_WIN32(GetLastError());
			if (SUCCEEDED(result))
				result = E_OUTOFMEMORY;
		} else {
			result = g_CreateGeometryFromRegion(region, &g_Reflection.geometry);
			DeleteObject(region);
		}
	}
	if (FAILED(result)) {
		LogFailure(g_ReflectionFailureLogged, L"Updating the snap reflection failed", result);
		return false;
	}
	g_ReflectionFailureLogged = false;
	return true;
}

bool EnsureReflection(void* list, void* owner, void* sheet, double opacity) {
	if (!g_ReflectionEnabled || !list || !owner || !sheet)
		return false;
	if (g_Reflection.visual && g_Reflection.sheet == sheet)
		return UpdateReflectionGeometry(list, owner, sheet, opacity);
	if (g_Reflection.visual)
		ResetReflectionResources();

	void* compositor = FindDesktopCompositor();
	if (!compositor)
		return false;

	void* visual{};
	void* brush{};
	void* geometry{};
	void* instruction{};
	HRESULT result = g_CreateRenderDataVisual(&visual);
	if (SUCCEEDED(result))
		result = g_CreateImageLegacyMilBrush(compositor, &brush);
	HRGN emptyRegion{};
	if (SUCCEEDED(result)) {
		emptyRegion = CreateRectRgn(0, 0, 0, 0);
		if (!emptyRegion) {
			result = HRESULT_FROM_WIN32(GetLastError());
			if (SUCCEEDED(result))
				result = E_OUTOFMEMORY;
		}
	}
	if (SUCCEEDED(result))
		result = g_CreateGeometryFromRegion(emptyRegion, &geometry);
	if (emptyRegion)
		DeleteObject(emptyRegion);
	if (SUCCEEDED(result))
		result = g_CreateDrawGeometryInstruction(brush, geometry, &instruction);
	if (SUCCEEDED(result))
		result = g_AddRenderInstruction(visual, instruction);
	ReleaseObjectIfPresent(instruction);
	if (FAILED(result)) {
		ReleaseObjectIfPresent(visual);
		ReleaseObjectIfPresent(brush);
		ReleaseObjectIfPresent(geometry);
		LogFailure(g_ReflectionFailureLogged, L"Creating the snap reflection visual failed", result);
		return false;
	}

	g_Reflection.visual = visual;
	g_Reflection.brush = brush;
	g_Reflection.geometry = geometry;
	g_Reflection.sheet = sheet;
	g_Reflection.list = list;
	g_Reflection.owner = owner;
	if (!UpdateReflectionGeometry(list, owner, sheet, opacity)) {
		ResetReflectionResources();
		return false;
	}
	return true;
}

void ReleaseFrames(RippleFrames& frames) {
	for (void*& frame : frames)
		ReleaseObjectIfPresent(frame);
}

bool AllFramesPresent(const RippleFrames& frames) {
	return std::all_of(frames.begin(), frames.end(), [](void* frame) {
		return frame != nullptr;
	});
}

bool EnsureRippleResources() {
	if (g_Ripple.container && g_Ripple.image && AllFramesPresent(g_Ripple.frames))
		return true;
	RippleFrames frames{};
	void* theme = g_GetTheme(0);
	HRESULT result = theme ? g_CreateBitmapsFromAtlasImageStrip(
		theme, g_RippleThemePart, g_RippleFrameCount, nullptr, frames.data()) : E_FAIL;
	if (FAILED(result) || !AllFramesPresent(frames)) {
		ReleaseFrames(frames);
		if (!g_Ripple.loggedUnavailable) {
			if (FAILED(result)) {
				Wh_Log(L"Theme atlas part 59 couldn't be split into 12 ripple frames: 0x%08X",
					static_cast<unsigned int>(result));
			} else {
				Wh_Log(L"Theme atlas part 59 returned an incomplete 12-frame ripple strip");
			}
			g_Ripple.loggedUnavailable = true;
		}
		return false;
	}
	void* container{};
	void* image{};
	result = CreateContainer(&container);
	if (SUCCEEDED(result))
		result = g_CreateImage(&image);
	if (SUCCEEDED(result))
		result = AddVisualChild(container, image);
	if (FAILED(result)) {
		ReleaseObjectIfPresent(image);
		ReleaseObjectIfPresent(container);
		ReleaseFrames(frames);
		Wh_Log(L"Ripple visual creation failed: 0x%08X", static_cast<unsigned int>(result));
		return false;
	}
	g_Ripple.frames = frames;
	g_Ripple.container = container;
	g_Ripple.image = image;
	g_Ripple.loggedUnavailable = false;
	return true;
}

void SetRippleFrame(unsigned int frameIndex) {
	if (!g_Ripple.image || frameIndex >= g_RippleFrameCount ||
		g_Ripple.frameIndex == static_cast<int>(frameIndex))
		return;
	HRESULT result = SetImageBitmapSource(g_Ripple.image, g_Ripple.frames[frameIndex]);
	if (FAILED(result))
		return;
	g_Ripple.frameIndex = static_cast<int>(frameIndex);
}

bool StopRipple() {
	g_Ripple.active = false;
	g_Ripple.sheet = nullptr;
	if (g_Ripple.image && g_Ripple.frames[g_RippleFrameCount - 1])
		SetRippleFrame(g_RippleFrameCount - 1);
	if (g_Ripple.container) {
		HRESULT result = g_RemoveSelfFromParent(g_Ripple.container);
		if (FAILED(result)) {
			Wh_Log(L"Removing the ripple visual failed: 0x%08X", static_cast<unsigned int>(result));
			return false;
		}
	}
	return true;
}

bool StartRipple(
	void* list,
	void* owner,
	void* sheet,
	POINT origin) {
	if (!StopRipple())
		return false;
	if (!EnsureRippleResources())
		return false;
	void* root = g_GetRootVisualForDesktop(list, WindowDesktopId(owner));
	void* reference = SnapReferenceVisual(list, owner);
	if (!root || !reference)
		return false;
	HRESULT result = g_RemoveSelfFromParent(g_Ripple.container);
	if (SUCCEEDED(result))
		result = InsertVisualRelative(root, g_Ripple.container, reference, true);
	if (FAILED(result)) {
		Wh_Log(L"Positioning the ripple visual failed: 0x%08X", static_cast<unsigned int>(result));
		return false;
	}
	SIZE logicalSize = BitmapSize(g_Ripple.frames[0]);
	unsigned int dpi = g_MonitorDpiFromPoint(origin);
	if (!dpi)
		dpi = USER_DEFAULT_SCREEN_DPI;
	int width = MulDiv(logicalSize.cx, dpi, USER_DEFAULT_SCREEN_DPI);
	int height = MulDiv(logicalSize.cy, dpi, USER_DEFAULT_SCREEN_DPI);
	if (width <= 0 || height <= 0 ||
		FAILED(SetVisualSize(g_Ripple.image, width, height))) {
		g_RemoveSelfFromParent(g_Ripple.container);
		return false;
	}
	g_SetInsetLeft(g_Ripple.image, origin.x - width / 2);
	g_SetInsetTop(g_Ripple.image, origin.y - height / 2);
	g_Ripple.frameIndex = -1;
	SetRippleFrame(0);
	g_Ripple.sheet = sheet;
	g_Ripple.startTime = AnimationTime();
	g_Ripple.active = true;
	return true;
}

void UpdateRipple(void* sheet) {
	if (!g_Ripple.active || g_Ripple.sheet != sheet)
		return;
	double elapsed = AnimationTime() - g_Ripple.startTime;
	double progress = std::clamp(elapsed / g_RippleDuration, 0.0, 1.0);
	unsigned int frameIndex = std::min(
		static_cast<unsigned int>(progress * g_RippleFrameCount),
		g_RippleFrameCount - 1);
	SetRippleFrame(frameIndex);
	if (progress >= 1.0 || !SheetRectAnimationActive(sheet))
		StopRipple();
}

double AnimationProgress(double now, double startTime, float duration) {
	if (!(duration > 0.0f))
		return 1.0;
	return std::clamp((now - startTime) / static_cast<double>(duration), 0.0, 1.0);
}

LONG InterpolateWin10Value(LONG source, LONG target, float progress) {
	if (source == target)
		return target;
	float value = (1.0f - progress) * static_cast<float>(source) +
		progress * static_cast<float>(target);
	LONG integer = static_cast<LONG>(value);
	return std::clamp(integer, std::min(source, target), std::max(source, target));
}

