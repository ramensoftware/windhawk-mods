void RecordNativeRect(
	void* sheet,
	const RECT* rect,
	float duration) {
	if (!sheet)
		return;
	if (g_CapturingArrangement) {
		g_NativeSnapCapture.sheet = sheet;
		if (rect) {
			g_NativeSnapCapture.rect = *rect;
			g_NativeSnapCapture.rectValid = true;
		}
		g_NativeSnapCapture.nativeAnimationActive =
			duration > g_DisabledAnimationDuration * 10.0f;
		g_NativeSnapCapture.nativeAnimationStateValid = true;
		g_NativeSnapCapture.animationEnabled =
			g_NativeSnapCapture.nativeAnimationActive;
		g_NativeSnapCapture.animationEnabledValid = true;
		return;
	}
	if (sheet == g_SnapSheet) {
		if (rect) {
			g_SnapRect = *rect;
			g_SnapRectValid = true;
		}
		g_SnapNativeAnimationActive =
			duration > g_DisabledAnimationDuration * 10.0f;
	}
}

