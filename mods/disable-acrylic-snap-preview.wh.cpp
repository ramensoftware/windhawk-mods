void* FindUniqueObjectByVtable(
	const void* owner,
	std::size_t begin,
	std::size_t end,
	void* expectedVtable) {
	if (!owner || !expectedVtable || begin > end)
		return nullptr;

	void* match{};
	for (std::size_t offset = begin; offset + sizeof(void*) <= end;
		offset += alignof(void*)) {
		void* candidate{};
		if (!TryReadField(owner, offset, &candidate) ||
			!IsReadableMemory(candidate, sizeof(void*))) {
			continue;
		}
		void* candidateVtable{};
		if (!TryReadField(candidate, 0, &candidateVtable) ||
			candidateVtable != expectedVtable) {
			continue;
		}
		if (match && match != candidate)
			return nullptr;
		match = candidate;
	}
	return match;
}

