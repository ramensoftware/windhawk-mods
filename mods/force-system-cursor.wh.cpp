/*
# Force System Cursor

Replaces a program's custom cursor with the system default cursor, or with a
built-in cursor, while letting the program hide the cursor normally.

## Choosing the target program

The mod targets nothing by default, so it does nothing until you tell it which
process to apply to. Open the mod in Windhawk, go to the **Advanced** tab, and
put the executable name of your target in the **Custom process inclusion list**.
The change applies as soon as you save, and takes effect the next time the
program starts.

## Settings

- **Enable custom cursor**: when on, use the built-in cursor (or the file set
  below); when off, use the system default cursor.
- **Custom cursor file path (optional)**: the full path of a `.cur` file to use
  instead of the built-in cursor. Leave empty to use the built-in one.
*/
